const execFileP = promisify(execFile);

export async function jsonAsync(bin, args, opts = {}) {
  try {
    const { stdout } = await execFileP(bin, args, { encoding: 'utf8', timeout: 30000, maxBuffer: 64 * 1024 * 1024, ...opts });
    return JSON.parse(stdout);
  } catch {
    return null;
  }
}

export function json(bin, args, opts = {}) {
  try {
    return JSON.parse(execFileSync(bin, args, { encoding: 'utf8', timeout: 30000, stdio: ['ignore', 'pipe', 'ignore'], ...opts }));
  } catch {
    return null;
  }
}

