const SCHEMA_LOCK = 7475;
const WRITE_LOCK = 7474;
const statements = new Map();

// SQLite-style ? placeholders, outside quotes, become $1, $2, …
export function numbered(sql) {
  if (statements.has(sql)) return statements.get(sql);
  let n = 0;
  let quote = null;
  let out = '';
  for (const ch of sql) {
    if (quote) { if (ch === quote) quote = null; out += ch; continue; }
    if (ch === "'" || ch === '"') quote = ch;
    out += ch === '?' ? `$${++n}` : ch;
  }
  statements.set(sql, out);
  return out;
}

function wrap(query, extra) {
  const q = (sql, params) => query(params.length ? numbered(sql) : sql, params.length ? params : undefined);
  return {
    ...extra,
    query: q,
    prepare: sql => ({
      get: async (...p) => (await q(sql, p)).rows[0],
      all: async (...p) => (await q(sql, p)).rows,
      run: async (...p) => ({ changes: (await q(sql, p)).rowCount }),
    }),
    exec: async sql => { await query(sql); },
  };
}

const pools = new Map();

// One pool per URL per process; the schema is migrated on first open and a DB newer than this code is refused.
export async function open(url = DATABASE_URL) {
  if (pools.has(url)) return pools.get(url);
  const pool = new pg.Pool({ connectionString: url, max: 10, allowExitOnIdle: true, connectionTimeoutMillis: 5000 });
  pool.on('error', () => {});
  const db = wrap((text, values) => pool.query(text, values), { pool, url, close: () => { pools.delete(url); return pool.end(); } });
  const ready = migrate(db).then(() => db, e => { pools.delete(url); pool.end().catch(() => {}); throw e; });
  pools.set(url, ready);
  return ready;
}

async function migrate(db) {
  const client = await db.pool.connect();
  try {
    await client.query('select pg_advisory_lock($1)', [SCHEMA_LOCK]);
    await client.query('create table if not exists schema_version (v integer not null)');
    const version = (await client.query('select max(v) as v from schema_version')).rows[0].v ?? 0;
    if (version > MIGRATIONS.length) {
      throw new Error(`the factory DB is at schema ${version} but this code knows ${MIGRATIONS.length}; pull dotclaude first.`);
    }
    for (let v = version; v < MIGRATIONS.length; v++) {
      await client.query('begin');
      try {
        await client.query(MIGRATIONS[v]);
        await client.query('insert into schema_version (v) values ($1)', [v + 1]);
        await client.query('commit');
      } catch (e) {
        await client.query('rollback');
        throw e;
      }
    }
  } finally {
    await client.query('select pg_advisory_unlock($1)', [SCHEMA_LOCK]).catch(() => {});
    client.release();
  }
}

// Every write transaction holds one advisory lock, so events commit in id order and no cursor ever passes an uncommitted id.
export async function tx(db, fn) {
  if (db.inTx) return fn(db);
  const client = await db.pool.connect();
  const t = wrap((text, values) => client.query(text, values), { pool: db.pool, url: db.url, inTx: true });
  try {
    await client.query('begin');
    await client.query('select pg_advisory_xact_lock($1)', [WRITE_LOCK]);
    const out = await fn(t);
    await client.query('commit');
    return out;
  } catch (e) {
    await client.query('rollback').catch(() => {});
    throw e;
  } finally {
    client.release();
  }
}

export function emit(db, type, subject = null, data = null, writes = []) {
  return tx(db, async t => {
    const { rows } = await t.query('insert into events (ts, type, subject, data) values (?, ?, ?, ?) returning id',
      [now(), type, subject, data == null ? null : JSON.stringify(data)]);
    for (const [sql, ...params] of writes) await t.query(sql, params);
    return rows[0].id;
  });
}

// Calls onNotify with each 'factory' notification's payload ("<event id> <type>", or "0 herdr"), and with null on every
// (re)connect so the caller catches up on what it missed while disconnected. Returns stop().
export function listen(onNotify, url = DATABASE_URL, retryMs = 2000) {
  let stopped = false;
  let client = null;
  const connect = () => {
    if (stopped) return;
    const c = new pg.Client({ connectionString: url });
    client = c;
    let retried = false;
    const retry = () => {
      if (retried || stopped) return;
      retried = true;
      c.end().catch(() => {});
      setTimeout(connect, retryMs);
    };
    c.on('notification', m => onNotify(m.payload));
    c.on('error', retry);
    c.on('end', retry);
    c.connect().then(() => c.query('listen factory')).then(() => onNotify(null), retry);
  };
  connect();
  return () => { stopped = true; client?.end().catch(() => {}); };
}

export async function maxId(db) {
  return (await db.prepare('select coalesce(max(id), 0) as m from events').get()).m;
}

async function cursorOf(db, name, machine) {
  const row = await db.prepare('select last_event_id from cursors where handler = ? and machine = ?').get(name, machine);
  if (row) return row.last_event_id;
  const start = await maxId(db);
  await db.prepare('insert into cursors (handler, machine, last_event_id) values (?, ?, ?) on conflict do nothing').run(name, machine, start);
  return start;
}

export function parse(row) {
  return row && { ...row, data: row.data ? JSON.parse(row.data) : {} };
}

// Feeds one handler every matching row past its cursor, in order. Follow-up events, state writes and the
// cursor commit in one transaction after run() returns; a throw stops this handler's round and the row repeats.
export async function dispatchOne(db, handler, ctx = {}) {
  const machine = ctx.machine ?? MACHINE;
  let done = 0;
  for (;;) {
    const cursor = await cursorOf(db, handler.name, machine);
    const top = await maxId(db);
    const marks = handler.on.map(() => '?').join(', ');
    const row = parse(await db.prepare(`select * from events where id > ? and id <= ? and type in (${marks}) order by id limit 1`).get(cursor, top, ...handler.on));
    if (!row) {
      if (top > cursor) await db.prepare('update cursors set last_event_id = ? where handler = ? and machine = ?').run(top, handler.name, machine);
      return done;
    }
    if (row.data.imported) {
      await db.prepare('update cursors set last_event_id = ? where handler = ? and machine = ?').run(row.id, handler.name, machine);
      continue;
    }
    const pending = [];
    const hctx = {
      ...ctx, db, machine,
      emit: (type, subject, data, writes = []) => pending.push({ type, subject, data, writes }),
      write: (sql, ...params) => pending.push({ writes: [[sql, ...params]] }),
    };
    try {
      await handler.run(row, hctx);
    } catch (e) {
      ctx.log?.(`handler ${handler.name} failed on event ${row.id} (${row.type}): ${e.message}`);
      return done;
    }
    await tx(db, async t => {
      for (const p of pending) {
        if (p.type) await emit(t, p.type, p.subject, p.data, p.writes);
        else for (const [sql, ...params] of p.writes) await t.query(sql, params);
      }
      await t.query('update cursors set last_event_id = ? where handler = ? and machine = ?', [row.id, handler.name, machine]);
    });
    done++;
  }
}

export async function dispatch(db, handlers, ctx = {}) {
  let done = 0;
  for (const h of handlers) done += await dispatchOne(db, h, ctx);
  return done;
}

